import Base64Client from "./Base64";
import { getBase64Seo } from "./content";
import { pageMetadata } from "@/lib/page-metadata";
import { parseLocale } from "@/lib/localized-path";
import ToolGuide, { ToolBreadcrumb } from "@/components/seo/ToolGuide";
type Props = { params: Promise<{ locale: string }> };
export async function generateMetadata({ params }: Props) {
 const locale = parseLocale((await params).locale); const seo = getBase64Seo(locale);
 return pageMetadata(locale, "/tools/base64", seo.title, seo.description, true);
}
export default async function Page({ params }: Props) {
 const locale = parseLocale((await params).locale);
 return <><ToolBreadcrumb slug="base64" locale={locale} /><Base64Client /><ToolGuide slug="base64" locale={locale} /></>;
}
